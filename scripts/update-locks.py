"""Maintainer tool: regenerate the hash-locked requirement files.

Reads ``requirements/{runtime,dev,build}.in`` (exact top-level pins), resolves
the full dependency set with pip's resolver (``pip install --dry-run --report``)
in a throw-away venv, then writes ``requirements/*.lock`` with the sha256 of
*every* file PyPI publishes for each pinned version, so the same lock installs
on Windows, Linux and macOS (x86_64 and arm64) with ``--require-hashes``.

It also checks that every compiled package ships a wheel for each supported
platform x Python 3.10-3.12, so that end users never need a compiler.

Needs internet access (PyPI). Only the Python standard library is used.

Usage:  python scripts/update-locks.py [--check]
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess  # nosec B404 - runs pip with fixed arguments
import sys
import tempfile
import urllib.request
import venv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQ = ROOT / "requirements"
PYPI_JSON = "https://pypi.org/pypi/{name}/{version}/json"

PYTHONS = ("310", "311", "312")
# platform label -> regex matched against a wheel's platform tag
PLATFORMS = {
    "win_amd64": r"win_amd64",
    "linux_x86_64": r"manylinux.*x86_64",
    "linux_aarch64": r"manylinux.*aarch64",
    "macos_x86_64": r"macosx.*(x86_64|universal2|intel)",
    "macos_arm64": r"macosx.*(arm64|universal2)",
}


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def resolve(python: Path, req_files: list[Path], workdir: Path) -> dict[str, str]:
    """Return {canonical_name: version} for the full resolved set."""
    report = workdir / f"report-{req_files[-1].stem}.json"
    cmd = [
        str(python),
        "-m",
        "pip",
        "install",
        "--dry-run",
        "--ignore-installed",
        "--quiet",
        "--report",
        str(report),
    ]
    for f in req_files:
        cmd += ["-r", str(f)]
    subprocess.run(cmd, check=True)  # nosec B603
    data = json.loads(report.read_text(encoding="utf-8"))
    return {canonical(i["metadata"]["name"]): i["metadata"]["version"] for i in data["install"]}


def pypi_files(name: str, version: str) -> list[dict[str, object]]:
    url = PYPI_JSON.format(name=name, version=version)
    with urllib.request.urlopen(url, timeout=60) as resp:  # nosec B310 - fixed https URL
        data = json.load(resp)
    return list(data["urls"])


def wheel_coverage_problems(name: str, files: list[dict[str, object]]) -> list[str]:
    wheels = [str(f["filename"]) for f in files if str(f["filename"]).endswith(".whl")]
    # pure-python wheel covers everything
    if any(w.endswith("-none-any.whl") for w in wheels):
        return []
    problems = []
    for py in PYTHONS:
        for label, plat_re in PLATFORMS.items():
            ok = False
            for w in wheels:
                parts = w[:-4].split("-")
                pytag, abitag, plattag = parts[-3], parts[-2], parts[-1]
                if not re.search(plat_re, plattag):
                    continue
                pys = pytag.split(".")
                if f"cp{py}" in pys or f"py{py[0]}" in pys or "py3" in pys:
                    ok = True
                elif "abi3" in abitag.split("."):
                    ok = any(p.startswith("cp3") and int(p[3:]) <= int(py[1:]) for p in pys)
                if ok:
                    break
            if not ok:
                problems.append(f"{name}: no wheel for cp{py} / {label}")
    return problems


def render_lock(title: str, pins: dict[str, str], header_note: str) -> tuple[str, list[str]]:
    lines = [
        f"# {title}",
        "# GENERATED by scripts/update-locks.py - do not edit by hand.",
        f"# {header_note}",
        "# Every hash PyPI publishes for each version is listed so this lock installs",
        "# on Windows, Linux and macOS with: pip install --require-hashes -r <lock>",
        "",
    ]
    problems: list[str] = []
    for name in sorted(pins):
        version = pins[name]
        files = pypi_files(name, version)
        problems += wheel_coverage_problems(name, files)
        hashes = sorted({str(f["digests"]["sha256"]) for f in files})  # type: ignore[index]
        lines.append(f"{name}=={version} \\")
        for i, h in enumerate(hashes):
            end = " \\" if i < len(hashes) - 1 else ""
            lines.append(f"    --hash=sha256:{h}{end}")
    return "\n".join(lines) + "\n", problems


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--check",
        action="store_true",
        help="fail if the generated locks differ from the committed ones",
    )
    args = ap.parse_args()

    with tempfile.TemporaryDirectory(prefix="apiedge-lock-") as tmp:
        work = Path(tmp)
        venv.EnvBuilder(with_pip=True).create(work / "venv")
        py = work / "venv" / ("Scripts/python.exe" if sys.platform == "win32" else "bin/python")
        subprocess.run(
            [
                str(py),
                "-m",
                "pip",
                "install",
                "--quiet",
                "-r",  # nosec B603
                str(REQ / "build.in"),
            ],
            check=True,
        )

        runtime = resolve(py, [REQ / "runtime.in"], work)
        dev_all = resolve(py, [REQ / "runtime.in", REQ / "dev.in"], work)
        build = resolve(py, [REQ / "build.in"], work)

    for name, ver in runtime.items():
        if dev_all.get(name) != ver:
            print(f"error: dev tools force {name} {dev_all.get(name)} != runtime {ver}")
            return 1
    dev = {n: v for n, v in dev_all.items() if n not in runtime}

    outputs = {
        "runtime.lock": render_lock(
            "APIEdge runtime lock", runtime, "Input: requirements/runtime.in"
        ),
        "dev.lock": render_lock(
            "APIEdge development lock (install together with runtime.lock)",
            dev,
            "Input: requirements/dev.in (resolved with runtime.in)",
        ),
        "build.lock": render_lock(
            "APIEdge installer/build tooling lock", build, "Input: requirements/build.in"
        ),
    }
    problems = [p for _, (_, probs) in outputs.items() for p in probs]
    changed = False
    for fname, (text, _) in outputs.items():
        target = REQ / fname
        old = target.read_text(encoding="utf-8") if target.exists() else ""
        if old != text:
            changed = True
            if not args.check:
                target.write_text(text, encoding="utf-8", newline="\n")
                print(f"wrote {target.relative_to(ROOT)}")
    for p in problems:
        print(f"warning: {p}")
    if args.check and changed:
        print("error: locks are out of date; run scripts/update-locks.py")
        return 1
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
